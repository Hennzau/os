layer_state_t layer_state_set_user(layer_state_t state) {
    return update_tri_layer_state(state, CONTROL, CODE, CONTROL_CODE);
}

bool process_record_user(uint16_t keycode, keyrecord_t *record) {
    if (
        record->event.pressed == false
        && keycode != ACC_CODE
    ) {
        clear_oneshot_layer_state(ONESHOT_PRESSED);
        clear_oneshot_mods();
        return true;
    }

    switch (keycode) {
        case CK_CARET: tap_code16(KC_LBRC); tap_code(KC_SPACE); return false;
        case CK_ECIR: tap_code16(KC_LBRC); tap_code(KC_E); return false;
        case CK_ACIR: tap_code16(KC_LBRC); tap_code(KC_Q); return false;
        case CK_ICIR: tap_code16(KC_LBRC); tap_code(KC_I); return false;
        case CK_OCIR: tap_code16(KC_LBRC); tap_code(KC_O); return false;
        case CK_UCIR: tap_code16(KC_LBRC); tap_code(KC_U); return false;

        case CK_EDIA: tap_code16(S(KC_LBRC)); tap_code(KC_E); return false;
        case CK_IDIA: tap_code16(S(KC_LBRC)); tap_code(KC_I); return false;

        case ACC_CODE: if (record->tap.count > 0 && record->event.pressed) {
            set_oneshot_layer(ACCENT, ONESHOT_START);
            return false;
        }
    }
    return true;
}
